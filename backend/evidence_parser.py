def parse_sqlite(file_path):
    events = []
    try:
        # SQLite read-only connection
        conn = sqlite3.connect(f"file:{file_path}?mode=ro", uri=True)
        cursor = conn.cursor()
        
        # Introspect table names
        cursor.execute("SELECT name FROM sqlite_master WHERE type='table'")
        tables = [row[0] for row in cursor.fetchall()]
        
        for table in tables:
            try:
                cursor.execute(f"PRAGMA table_info({table})")
                columns = cursor.fetchall()
                col_names = [col[1] for col in columns]
                
                # Check for timestamp columns
                time_cols = []
                for name in col_names:
                    lower_name = name.lower()
                    if any(k in lower_name for k in ["time", "date", "created", "updated", "stamp", "epoch"]):
                        time_cols.append(name)
                
                if not time_cols:
                    continue
                
                # Choose the first match as key timestamp
                time_col = time_cols[0]
                desc_cols = [c for c in col_names if c != time_col][:5]
                desc_select = " || ' | ' || ".join([f"COALESCE(CAST({c} AS TEXT), 'NULL')" for c in desc_cols])
                if not desc_select:
                    desc_select = "'Entry Row'"
                
                query = f"SELECT {time_col}, {desc_select} FROM {table}"
                cursor.execute(query)
                rows = cursor.fetchall()
                
                for row in rows:
                    raw_time = row[0]
                    desc = f"Table: {table} | {row[1]}"
                    timestamp_utc = normalize_sqlite_timestamp(raw_time)
                    
                    events.append({
                        "timestamp_utc": timestamp_utc,
                        "event_type": f"Database Entry ({table})",
                        "description": desc,
                        "source_field": os.path.basename(file_path)
                    })
            except Exception as table_err:
                print(f"Error parsing table {table}: {table_err}")
                
        conn.close()
    except Exception as e:
        print(f"Failed to parse SQLite database: {e}")
        
    return events

def parse_file(file_path):
    # Determine type based on extension
    ext = os.path.splitext(file_path)[1].lower()
    if ext == '.evtx':
        return parse_evtx(file_path)
    elif ext in ['.sqlite', '.db', '.sqlite3']:
        return parse_sqlite(file_path)
    else:
        raise ValueError(f"Unsupported file type: {ext}")

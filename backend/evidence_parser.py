import os
import sqlite3
import datetime
import xml.etree.ElementTree as ET

def normalize_sqlite_timestamp(raw_val):
    if not raw_val:
        return "Unknown"
    if isinstance(raw_val, str):
        raw_val = raw_val.strip()
        if raw_val.isdigit():
            raw_val = int(raw_val)
        else:
            # Parse standard datetime string formats
            for fmt in ("%Y-%m-%d %H:%M:%S", "%Y-%m-%d %H:%M:%S.%f", "%Y-%m-%dT%H:%M:%SZ", "%Y-%m-%dT%H:%M:%S.%fZ", "%Y-%m-%d %H:%M:%S %z"):
                try:
                    # Strip timezone offsets for simple UTC normalization if present
                    if '+' in raw_val:
                        parts = raw_val.split('+')
                        dt = datetime.datetime.strptime(parts[0].strip(), "%Y-%m-%d %H:%M:%S")
                    else:
                        dt = datetime.datetime.strptime(raw_val, fmt)
                    return dt.strftime("%Y-%m-%dT%H:%M:%SZ")
                except ValueError:
                    pass
            return raw_val
            
    if isinstance(raw_val, (int, float)):
        val_str = str(int(raw_val))
        try:
            if len(val_str) == 10:  # Unix timestamp seconds
                dt = datetime.datetime.fromtimestamp(raw_val, datetime.timezone.utc)
                return dt.strftime("%Y-%m-%dT%H:%M:%SZ")
            elif len(val_str) == 13:  # Unix timestamp milliseconds
                dt = datetime.datetime.fromtimestamp(raw_val / 1000.0, datetime.timezone.utc)
                return dt.strftime("%Y-%m-%dT%H:%M:%SZ")
            elif len(val_str) >= 16:  # Chrome/Webkit timestamp (microseconds since 1601-01-01)
                # 11644473600 is seconds between 1601 and 1970
                seconds = raw_val / 1000000.0 - 11644473600
                dt = datetime.datetime.fromtimestamp(seconds, datetime.timezone.utc)
                return dt.strftime("%Y-%m-%dT%H:%M:%SZ")
        except Exception:
            pass
    return str(raw_val)

def parse_evtx(file_path):
    # Ensure dependencies are loaded
    try:
        import Evtx.Evtx as evtx
    except ImportError:
        print("python-evtx library is missing. Falling back to mock data.")
        return get_mock_evtx_events(file_path)

    # Check for placeholder files
    with open(file_path, "rb") as f:
        header = f.read(100)
    if b"Placeholder" in header or len(header) < 100:
        print("Mock/Placeholder EVTX file detected. Returning sample logs.")
        return get_mock_evtx_events(file_path)

    events = []
    try:
        with evtx.Evtx(file_path) as log:
            for record in log.records():
                try:
                    xml_str = record.xml()
                    root = ET.fromstring(xml_str)
                    ns = '{http://schemas.microsoft.com/win/2004/08/events/event}'
                    system = root.find(f'.//{ns}System')
                    if system is not None:
                        # Extract TimeCreated
                        time_created_el = system.find(f'{ns}TimeCreated')
                        timestamp_utc = time_created_el.get('SystemTime') if time_created_el is not None else None
                        if timestamp_utc:
                            if ' ' in timestamp_utc:
                                timestamp_utc = timestamp_utc.replace(' ', 'T')
                            if not timestamp_utc.endswith('Z') and '+' not in timestamp_utc:
                                timestamp_utc += 'Z'
                        
                        # Extract EventID
                        event_id_el = system.find(f'{ns}EventID')
                        event_id = event_id_el.text if event_id_el is not None else "Unknown"
                        
                        # Extract Provider
                        provider_el = system.find(f'{ns}Provider')
                        provider = provider_el.get('Name') if provider_el is not None else "Unknown"
                        
                        # Extract EventData for description message
                        msg = f"EventID {event_id} generated by {provider}."
                        event_data = root.find(f'.//{ns}EventData')
                        if event_data is not None:
                            data_elements = event_data.findall(f'{ns}Data')
                            data_details = []
                            for el in data_elements:
                                name = el.get('Name')
                                val = el.text
                                if name and val:
                                    data_details.append(f"{name}={val}")
                                elif val:
                                    data_details.append(val)
                            if data_details:
                                msg += " Data: " + ", ".join(data_details[:5])
                        
                        events.append({
                            "timestamp_utc": timestamp_utc or "Unknown",
                            "event_type": f"Windows Event ({event_id})",
                            "description": msg,
                            "source_field": os.path.basename(file_path)
                        })
                except Exception as e:
                    print(f"Skipping record due to parse error: {e}")
    except Exception as e:
        print(f"Failed to parse EVTX file: {e}")
        return get_mock_evtx_events(file_path)
        
    return events

